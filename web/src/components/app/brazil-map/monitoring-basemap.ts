import type { ExpressionSpecification, LayerSpecification } from "maplibre-gl";
import { VECTOR_SOURCE_ID } from "./basemaps";

const LOCAL_NAME: ExpressionSpecification = ["coalesce", ["get", "name:pt"], ["get", "name"], ["get", "name:latin"], ["get", "name_en"], ""];
const LINE_GEOMETRY: ExpressionSpecification = ["==", ["geometry-type"], "LineString"];
const POLYGON_GEOMETRY: ExpressionSpecification = ["==", ["geometry-type"], "Polygon"];

/** A compact, two-dimensional OpenMapTiles style designed around monitoring overlays. */
export const monitoringLayers = (dark: boolean): LayerSpecification[] => {
    const colors = dark
        ? {
              land: "#252e36",
              forest: "#2b403a",
              park: "#31473c",
              urban: "#303a43",
              water: "#163747",
              river: "#39728b",
              road: "#66747f",
              majorRoad: "#9d9a87",
              casing: "#26313b",
              building: "#3e4a54",
              label: "#cbd7df",
              mutedLabel: "#9cb3c0",
              halo: "#222c34",
          }
        : {
              land: "#f0f2ec",
              forest: "#dae6d6",
              park: "#d3e4ce",
              urban: "#e8eae5",
              water: "#b5d8e3",
              river: "#75afc2",
              road: "#ffffff",
              majorRoad: "#f3e3bc",
              casing: "#c9cdc7",
              building: "#d5dad3",
              label: "#354c5a",
              mutedLabel: "#557686",
              halo: "#f7f8f3",
          };
    const source = VECTOR_SOURCE_ID;
    const labelPaint = { "text-color": colors.label, "text-halo-color": colors.halo, "text-halo-width": 1.4 };

    return [
        { id: "monitoring-background", type: "background", paint: { "background-color": colors.land } },
        {
            id: "monitoring-landcover",
            type: "fill",
            source,
            "source-layer": "landcover",
            minzoom: 5,
            filter: ["all", POLYGON_GEOMETRY, ["match", ["get", "class"], ["wood", "grass"], true, false]],
            paint: { "fill-color": colors.forest, "fill-opacity": 0.7 },
        },
        {
            id: "monitoring-urban",
            type: "fill",
            source,
            "source-layer": "landuse",
            minzoom: 7,
            filter: ["all", POLYGON_GEOMETRY, ["match", ["get", "class"], ["residential", "commercial", "industrial"], true, false]],
            paint: { "fill-color": colors.urban, "fill-opacity": 0.7 },
        },
        {
            id: "monitoring-parks",
            type: "fill",
            source,
            "source-layer": "landuse",
            minzoom: 8,
            filter: ["all", POLYGON_GEOMETRY, ["match", ["get", "class"], ["park", "forest", "cemetery"], true, false]],
            paint: { "fill-color": colors.park },
        },
        { id: "monitoring-water", type: "fill", source, "source-layer": "water", filter: POLYGON_GEOMETRY, paint: { "fill-color": colors.water } },
        {
            id: "monitoring-waterways",
            type: "line",
            source,
            "source-layer": "waterway",
            minzoom: 7,
            filter: LINE_GEOMETRY,
            layout: { "line-cap": "round", "line-join": "round" },
            paint: { "line-color": colors.river, "line-width": ["interpolate", ["linear"], ["zoom"], 7, 0.5, 14, 2.5] },
        },
        {
            id: "monitoring-road-casing",
            type: "line",
            source,
            "source-layer": "transportation",
            minzoom: 7,
            filter: ["all", LINE_GEOMETRY, ["match", ["get", "class"], ["motorway", "trunk", "primary", "secondary", "tertiary"], true, false]],
            layout: { "line-cap": "round", "line-join": "round" },
            paint: { "line-color": colors.casing, "line-width": ["interpolate", ["linear"], ["zoom"], 7, 1, 12, 3.5, 18, 12] },
        },
        {
            id: "monitoring-local-roads",
            type: "line",
            source,
            "source-layer": "transportation",
            minzoom: 12,
            filter: ["all", LINE_GEOMETRY, ["match", ["get", "class"], ["minor", "service", "track"], true, false]],
            layout: { "line-cap": "round", "line-join": "round" },
            paint: { "line-color": colors.road, "line-opacity": 0.7, "line-width": ["interpolate", ["linear"], ["zoom"], 12, 0.7, 16, 3, 18, 6] },
        },
        {
            id: "monitoring-major-roads",
            type: "line",
            source,
            "source-layer": "transportation",
            minzoom: 7,
            filter: ["all", LINE_GEOMETRY, ["match", ["get", "class"], ["motorway", "trunk", "primary", "secondary", "tertiary"], true, false]],
            layout: { "line-cap": "round", "line-join": "round" },
            paint: { "line-color": colors.majorRoad, "line-width": ["interpolate", ["linear"], ["zoom"], 7, 0.5, 12, 2, 18, 9] },
        },
        {
            id: "monitoring-buildings",
            type: "fill",
            source,
            "source-layer": "building",
            minzoom: 14,
            filter: POLYGON_GEOMETRY,
            paint: { "fill-color": colors.building, "fill-opacity": 0.65 },
        },
        {
            id: "monitoring-water-labels",
            type: "symbol",
            source,
            "source-layer": "water_name",
            minzoom: 6,
            filter: ["==", ["geometry-type"], "Point"],
            layout: { "text-field": LOCAL_NAME, "text-font": ["Noto Sans Regular"], "text-size": 11, "text-max-width": 9 },
            paint: { ...labelPaint, "text-color": colors.mutedLabel },
        },
        {
            id: "monitoring-road-labels",
            type: "symbol",
            source,
            "source-layer": "transportation_name",
            minzoom: 13,
            filter: LINE_GEOMETRY,
            layout: {
                "symbol-placement": "line",
                "symbol-spacing": 400,
                "text-field": LOCAL_NAME,
                "text-font": ["Noto Sans Regular"],
                "text-size": 11,
                "text-max-angle": 30,
            },
            paint: { ...labelPaint, "text-color": colors.mutedLabel },
        },
        {
            id: "monitoring-towns",
            type: "symbol",
            source,
            "source-layer": "place",
            minzoom: 8,
            filter: ["match", ["get", "class"], ["town", "village", "hamlet", "suburb"], true, false],
            layout: {
                "text-field": LOCAL_NAME,
                "text-font": ["Noto Sans Regular"],
                "text-size": ["interpolate", ["linear"], ["zoom"], 8, 10, 14, 13],
                "text-max-width": 9,
                "text-padding": 10,
            },
            paint: labelPaint,
        },
        {
            id: "monitoring-cities",
            type: "symbol",
            source,
            "source-layer": "place",
            minzoom: 4,
            filter: ["==", ["get", "class"], "city"],
            layout: {
                "text-field": LOCAL_NAME,
                "text-font": ["Noto Sans Regular"],
                "text-size": ["interpolate", ["linear"], ["zoom"], 4, 11, 10, 14],
                "text-max-width": 9,
                "text-padding": 14,
                "symbol-sort-key": ["coalesce", ["get", "rank"], 10],
            },
            paint: labelPaint,
        },
        {
            id: "monitoring-countries",
            type: "symbol",
            source,
            "source-layer": "place",
            maxzoom: 5,
            filter: ["==", ["get", "class"], "country"],
            layout: {
                "text-field": LOCAL_NAME,
                "text-font": ["Noto Sans Regular"],
                "text-size": 12,
                "text-transform": "uppercase",
                "text-letter-spacing": 0.12,
                "text-padding": 18,
            },
            paint: { ...labelPaint, "text-color": colors.mutedLabel },
        },
    ];
};
